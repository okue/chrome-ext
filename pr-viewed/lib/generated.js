(function (root) {
  'use strict';

  // ---------------------------------------------------------------------------
  // isGeneratedFile (generated-file-check.ts)
  // ---------------------------------------------------------------------------

  const EXACT_FILENAMES = new Set([
    'package-lock.json',
    'pnpm-lock.yaml',
    'yarn.lock',
    'Gemfile.lock',
    'Pipfile.lock',
    'composer.lock',
    'Cargo.lock',
    'poetry.lock',
    'go.sum',
    'go.mod',
    'pubspec.lock',
    'flake.lock',
    'Package.resolved',
    'packages.lock.json',
    '.terraform.lock.hcl',
    'bun.lockb',
    'gradle.lockfile',
    'uv.lock',
    'pdm.lock',
  ]);

  const FILENAME_SUFFIXES = [
    '.min.js', '.min.css', '.bundle.js', '.bundle.css', '-min.js', '.map',
    '.pb.go', '.pb.rb', '.pb.py', '.pb.js', '.pb.cc', '.pb.h', '.pb2.py', '_pb2.py',
    '.grpc.pb.go', '_string.go',
    '.graphql.ts', '.graphql.js', '.openapi.ts', '.openapi.js',
    '.msw.ts', '.zod.ts', '.api.ts',
    '.g.dart', '.freezed.dart', '.g.cs', '.designer.cs',
    '_ide_helper.php',
  ];

  const ROOT_PATH_PREFIXES = ['vendor/', 'node_modules/', 'dist/', 'build/', 'out/'];
  const PATH_SEGMENTS = ['/generated/', '/gen/', '/__generated__/'];

  const isWordString = (text) => /^[0-9A-Za-z_]+$/.test(text);

  function hasGeneratedSuffix(fileName, marker) {
    const i = fileName.lastIndexOf(marker);
    return i !== -1 && isWordString(fileName.slice(i + marker.length));
  }

  const PATH_MATCHERS = [
    { description: 'exact-filename', matches: (_p, f) => EXACT_FILENAMES.has(f) },
    {
      description: 'minified-or-generated-suffix',
      matches: (_p, f) => FILENAME_SUFFIXES.some((s) => f.endsWith(s)),
    },
    {
      description: 'generated-extension',
      matches: (_p, f) => hasGeneratedSuffix(f, '.generated.') || hasGeneratedSuffix(f, '.gen.'),
    },
    { description: 'mockgen-go', matches: (_p, f) => f.startsWith('mock_') && f.endsWith('.go') },
    { description: 'mocks-go-directory', matches: (p, f) => p.includes('mocks/') && f.endsWith('.go') },
    {
      description: 'root-generated-directory',
      matches: (p) => ROOT_PATH_PREFIXES.some((prefix) => p.startsWith(prefix)),
    },
    {
      description: 'generated-path-segment',
      matches: (p) => PATH_SEGMENTS.some((segment) => p.includes(segment)),
    },
  ];

  const UNIVERSAL_PATTERNS = [
    /@generated\b/,
    /\bDO NOT EDIT\b/i,
    /\bDO NOT MODIFY\b/i,
    /\bAUTO[- ]?GENERATED\b/i,
    /\bTHIS FILE IS GENERATED\b/i,
    /\bGENERATED CODE\b/i,
    /\bMACHINE GENERATED\b/i,
    /Generated by\b/i,
    /Autogenerated by\b/i,
    /Created by .* - DO NOT EDIT/i,
    /This file was generated/i,
    /This is a generated file/i,
    /<auto-generated\s*\/?>/i,
    /<!-- Generated by/i,
  ];

  const LANGUAGE_SPECIFIC = [
    {
      extensions: ['.go'],
      patterns: [
        /^\/\/ Code generated .* DO NOT EDIT\.$/m,
        /Code generated by protoc-gen-go/,
        /Code generated by Wire/,
        /Code generated by ent/,
        /Code generated by sqlc/,
        /Code generated by MockGen/,
        /Code generated by go-swagger/,
        /Code generated by "stringer"/,
      ],
    },
    {
      extensions: ['.js', '.ts', '.jsx', '.tsx', '.mjs', '.cjs'],
      patterns: [
        /generated using openapi-typescript-codegen/i,
        /This file was auto-generated by openapi/i,
        /Generated by orval/i,
        /THIS FILE WAS GENERATED/,
        /Generated by graphql-codegen/i,
        /Prisma Client JS/,
        /Generated by the protocol buffer/,
        /GENERATED CODE -- DO NOT EDIT/,
        /@generated SignedSource/,
        /Generated by Apollo/,
      ],
    },
    {
      extensions: ['.rb'],
      patterns: [
        /This file is auto-generated from the current state of the database/,
        /This file is autogenerated/,
        /Generated by the protocol buffer/,
        /Autogenerated by Thrift/,
        /DO NOT MODIFY.*schema/i,
      ],
    },
    {
      extensions: ['.php'],
      patterns: [
        /This class was generated by/i,
        /Doctrine .* Generated/i,
        /Generated by the protocol buffer/,
        /auto-generated by Symfony/i,
      ],
    },
    {
      extensions: ['.py'],
      patterns: [
        /Generated by the protocol buffer compiler/,
        /@generated by mypy-protobuf/,
        /Generated by the gRPC/,
        /Autogenerated by Thrift/,
        /# Generated by Django/,
        /autogenerated by sqlacodegen/i,
        /generated by datamodel-codegen/,
      ],
    },
    {
      extensions: ['.java', '.kt'],
      patterns: [
        /Generated by the protocol buffer/,
        /@javax\.annotation\.Generated/,
        /@Generated\(/,
        /Generated by the gRPC/,
        /Generated by Dagger/,
        /generated at.*by JAXB/i,
        /OpenAPI Generator/,
      ],
    },
    {
      extensions: ['.cs'],
      patterns: [
        /<auto-generated>/,
        /<autogenerated>/,
        /Generated by the protocol buffer/,
        /auto-generated by EF/i,
        /This code was generated by a tool/,
      ],
    },
  ];

  /** Path-only check (difit layer 1). */
  function isGeneratedPath(path) {
    const fileName = path.split('/').pop() || '';
    for (const m of PATH_MATCHERS) {
      if (m.matches(path, fileName)) return { isGenerated: true, reason: 'path', matchedPattern: m.description };
    }
    return { isGenerated: false };
  }

  /** Content check on the first lines of the file (difit layers 2 & 3). */
  function isGeneratedContent(path, headerLines) {
    const fileName = path.split('/').pop() || '';
    // difit skips markdown: docs often contain example "generated" headers.
    if (/\.(md|markdown)$/i.test(fileName)) return { isGenerated: false };
    const header = headerLines.join('\n');
    for (const p of UNIVERSAL_PATTERNS) {
      if (p.test(header)) return { isGenerated: true, reason: 'universal', matchedPattern: p.source };
    }
    const ext = (path.match(/\.[a-zA-Z0-9]+$/) || [''])[0];
    const lang = LANGUAGE_SPECIFIC.find((l) => l.extensions.includes(ext));
    for (const p of lang ? lang.patterns : []) {
      if (p.test(header)) return { isGenerated: true, reason: 'language-specific', matchedPattern: p.source };
    }
    return { isGenerated: false };
  }

  function isMarkdown(path) {
    return /\.(md|markdown)$/i.test(path);
  }

  // ---------------------------------------------------------------------------
  // Glob matching for user-defined auto-viewed patterns (autoViewedPatterns.ts)
  // ---------------------------------------------------------------------------

  const normalizePath = (v) => v.replaceAll('\\', '/').replace(/^\.\/+/, '');
  const escapeRegex = (v) => v.replace(/[|\\{}()[\]^$+?.]/g, '\\$&');

  function matchesSegment(pathSegment, patternSegment) {
    let src = '^';
    for (const ch of patternSegment) {
      if (ch === '*') src += '.*';
      else if (ch === '?') src += '.';
      else src += escapeRegex(ch);
    }
    return new RegExp(src + '$').test(pathSegment);
  }

  function matchesPathSegments(pathSegs, patSegs, pi = 0, qi = 0) {
    if (qi >= patSegs.length) return pi >= pathSegs.length;
    const cur = patSegs[qi];
    if (cur === '**') {
      if (qi + 1 >= patSegs.length) return true;
      for (let n = pi; n <= pathSegs.length; n++) {
        if (matchesPathSegments(pathSegs, patSegs, n, qi + 1)) return true;
      }
      return false;
    }
    const seg = pathSegs[pi];
    if (!seg || !matchesSegment(seg, cur)) return false;
    return matchesPathSegments(pathSegs, patSegs, pi + 1, qi + 1);
  }

  const splitSegs = (v) => normalizePath(v).split('/').filter(Boolean);

  function parsePatterns(input) {
    const set = new Set();
    for (const line of String(input || '').split(/\r?\n/)) {
      const t = line.trim();
      if (t && !t.startsWith('#')) set.add(normalizePath(t));
    }
    return [...set];
  }

  function matchesPattern(filePath, pattern) {
    const p = normalizePath(pattern.trim());
    if (!p) return false;
    const fp = normalizePath(filePath);
    // Patterns without "/" match the basename, so `*.test.ts` works anywhere.
    if (!p.includes('/')) return matchesSegment(fp.split('/').pop() || fp, p);
    return matchesPathSegments(splitSegs(fp), splitSegs(p));
  }

  function matchesAnyPattern(filePath, patterns) {
    return patterns.some((p) => matchesPattern(filePath, p));
  }

  // ---------------------------------------------------------------------------
  // .gitattributes `linguist-generated` (difit uses `git check-attr`; this is a
  // root-.gitattributes-only approximation)
  // ---------------------------------------------------------------------------

  /** Returns [{pattern, value: true|false}] in file order. */
  function parseGitattributes(text) {
    const rules = [];
    for (const raw of String(text || '').split(/\r?\n/)) {
      const line = raw.trim();
      if (!line || line.startsWith('#')) continue;
      const [pattern, ...attrs] = line.split(/\s+/);
      for (const a of attrs) {
        if (a === 'linguist-generated' || a === 'linguist-generated=true') rules.push({ pattern, value: true });
        else if (a === '-linguist-generated' || a === '!linguist-generated' || a === 'linguist-generated=false') {
          rules.push({ pattern, value: false });
        }
      }
    }
    return rules;
  }

  function isLinguistGenerated(path, rules) {
    let result = false;
    for (const r of rules) {
      let pat = r.pattern;
      if (pat.endsWith('/')) continue; // gitattributes never matches directories
      // Leading "/" anchors to the root; patterns without "/" match the basename.
      if (pat.startsWith('/')) pat = pat.slice(1);
      if (matchesPattern(path, pat)) result = r.value; // last match wins
    }
    return result;
  }

  root.PRV = Object.assign(root.PRV || {}, {
    isGeneratedPath,
    isGeneratedContent,
    isMarkdown,
    parsePatterns,
    matchesAnyPattern,
    parseGitattributes,
    isLinguistGenerated,
  });
})(globalThis);
